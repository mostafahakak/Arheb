const LocaleContext = createContext(null);
const STORAGE_KEY = 'storeApp.locale';

export function LocaleProvider({ children }) {
  const [locale, setLocaleState] = useState('en');

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((v) => {
      if (v === 'en' || v === 'ar') setLocaleState(v);
    });
  }, []);

  const setLocale = useCallback((next) => {
    setLocaleState(next);
    AsyncStorage.setItem(STORAGE_KEY, next).catch(() => {});
  }, []);

  const t = useCallback(
    (key) => {
      const table = STRINGS[locale] || STRINGS.en;
      return table[key] ?? STRINGS.en[key] ?? key;
    },
    [locale],
  );

  const value = useMemo(
    () => ({ locale, setLocale, t, isRTL: locale === 'ar' }),
    [locale, setLocale, t],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error('useLocale must be used within LocaleProvider');
  return ctx;
}

/** Pick AR/EN value from a store/product-like object based on current locale. */
export function pickName(locale, obj) {
  if (!obj) return '';
  if (locale === 'ar') return obj.nameAr || obj.name || obj.nameEn || '';
  return obj.nameEn || obj.name || obj.nameAr || '';
}
